// Writes emoji/src/data.ts from the emojibase-data dev dependency (MIT, from Unicode's own data): the emoji with their
// names and a few search words, by group. Run it when that package is updated; the output is committed, so building
// the add-on needs nothing but this repository.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";

const require = createRequire(import.meta.url);
const data = require("emojibase-data/en/data.json");
const messages = require("emojibase-data/en/messages.json");

const keys = messages.groups.filter((g) => g.key !== "component").map((g) => g.key);
const titles = {
  "smileys-emotion": "Smileys & emotion",
  "people-body": "People & body",
  "animals-nature": "Animals & nature",
  "food-drink": "Food & drink",
  "travel-places": "Travel & places",
  activities: "Activities",
  objects: "Objects",
  symbols: "Symbols",
  flags: "Flags",
};
const groups = keys.map(() => []);
for (const e of data) {
  if (e.group === undefined) continue;
  const key = messages.groups.find((g) => g.order === e.group)?.key;
  const at = keys.indexOf(key);
  if (at < 0) continue;
  // A skin tone is offered only where it is one pictograph plus a modifier (a hand, a person), not for joined sequences.
  const tone = e.skins && [...e.emoji.replace(/️/g, "")].length === 1 ? 1 : 0;
  // One spelling for one emoji: a pictograph that is already drawn as an emoji needs no variation selector, which is
  // how the quick row writes it too (a text-first one, like the heart, keeps it).
  const emoji = /^\p{Emoji_Presentation}\uFE0F$/u.test(e.emoji) ? e.emoji.slice(0, -1) : e.emoji;
  groups[at].push([emoji, e.label, (e.tags ?? []).slice(0, 3).join(" "), tone]);
}
const out = `// Generated by scripts/make-emoji.mjs from emojibase-data (MIT, from Unicode's emoji data). Do not edit.
/** Each group's name. */
export const GROUPS: readonly string[] = ${JSON.stringify(keys.map((k) => titles[k] ?? k))};
/** By group: the emoji, its name, a few search words, and whether a skin tone applies (1) or not (0). */
export const EMOJI: readonly (readonly [string, string, string, 0 | 1])[][] = ${JSON.stringify(groups)};
`;
writeFileSync(new URL("../emoji/src/data.ts", import.meta.url), out);
console.log(`${groups.reduce((n, g) => n + g.length, 0)} emoji in ${keys.length} groups`);
